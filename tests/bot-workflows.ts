class Statement {
  args:any[]=[];
  constructor(public query:string){}
  bind(...args:any[]){this.args=args;return this;}
  execute(){
    const stmt=sql.prepare(this.query);
    const results=stmt.columns().length ? stmt.all(...this.args) : (stmt.run(...this.args),[]);
    return {results,success:true,meta:{changes:Number((sql.prepare('SELECT changes() AS n').get() as any).n)}};
  }
  async first(){return this.execute().results[0]||null;}
  async all(){return this.execute();}
  async run(){return this.execute();}
}
